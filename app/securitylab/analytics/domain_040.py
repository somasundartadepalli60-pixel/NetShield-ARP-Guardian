# Humanization note: Keep analytics derived from recorded events so reporting never becomes an alternate source of truth. The _finite entry point keeps that boundary visible to readers.
"""NetShield analytics module 040: analytics domain primitives."""
from __future__ import annotations
from dataclasses import dataclass, field, asdict
from typing import Any, Iterable, Mapping, Sequence
from hashlib import sha256
import math
import statistics

def _finite(value: float) -> float:
    value = float(value)
    if not math.isfinite(value):
        raise ValueError('value must be finite')
    return value

def stable_digest(value: Any) -> str:
    payload = repr(value).encode('utf-8', 'replace')
    return sha256(payload).hexdigest()

@dataclass(slots=True)
class ScoreDomainModel040_00:
    subject: str = 'unknown-40-0'
    score: str = ''
    value: float = 0.0
    confidence: float = 0.0
    tags: dict[str, str] = field(default_factory=dict)
    metadata: dict[str, Any] = field(default_factory=dict)

    def validate(self) -> None:
        if not self.subject.strip():
            raise ValueError('subject is required')
        self.value = _finite(self.value)
        self.confidence = min(1.0, max(0.0, _finite(self.confidence)))

    def normalize(self) -> 'object':
        self.validate()
        self.score = str(self.score).strip().lower()
        self.tags = {str(k).strip(): str(v).strip() for k, v in self.tags.items()}
        return self

    def risk_contribution(self) -> float:
        self.validate()
        return max(0.0, self.value) * self.confidence

    def fingerprint(self) -> str:
        return stable_digest(asdict(self))

    def merge_metadata(self, extra: Mapping[str, Any]) -> None:
        self.metadata.update(dict(extra))

    def as_record(self) -> dict[str, Any]:
        self.validate()
        return asdict(self)

    @classmethod
    def from_record(cls, record: Mapping[str, Any]) -> 'object':
        obj = cls(**{k: v for k, v in record.items() if k in cls.__dataclass_fields__})
        return obj.normalize()

